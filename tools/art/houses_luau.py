"""Writes tools/studio/place_houses.luau from the OBJ bounds and art/kit/houses/assets.json. Edit this file, not that one.
Also writes tools/studio/recolour_houses.luau: swaps replaced sheets for their new ids on every house in the place, hand-placed copies too, moving nothing.
  python tools/art/houses_luau.py
"""
import json
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
A = json.load(open(os.path.join(ROOT, "art", "kit", "houses", "assets.json")))
SHEETS = ("Frame", "Joinery", "Walls", "Roof", "Stone")
# plain invisible blocking, local to the house's ground centre: centre x y z, size x y z, and an optional tilt about x in degrees. The door faces local +z
COLLIDE = {
	"Cottage": [(0, 8, 0, 21, 18, 12), (12, 5, -2.6, 3.7, 12, 2.7)],
	"Townhouse": [(0, 13, 0, 14, 28, 11)],
	"Farmhouse": [(0, 7, 0, 26, 16, 13.2)],
	"Bridgehouse": [(-7.1, 6, 0, 5, 12, 11.2), (7.1, 6, 0, 5, 12, 11.2), (0, 17, 0, 20, 11, 12.4), (11.2, 11.05, -3, 3.2, 1, 7.3), (11.2, 5.3, 6.55, 3.2, 1, 16.6, 44)],
	"Inn": [(0, 10, 0.5, 28, 20, 16)],
	"Mill": [(0, 11, 0, 17.2, 22, 12.8), (10.8, 5.6, -0.7, 3, 12.4, 12.4)],
	"Smithy": [(0, 7, -6.2, 18, 14, 0.8), (8.8, 7, 0, 0.8, 14, 12.8), (-8.8, 7, 0, 0.8, 14, 12.8), (4.6, 4, -3.9, 5.8, 8, 4)],
	"Clocktower": [(-10.5, 19, 0, 11.2, 38, 11.2), (7, 10, 0, 24, 20, 12.8)],
	"Manor": [(0, 10, 0, 23, 20, 14), (-17, 10, 0, 11, 20, 18.4), (17, 10, 0, 11, 20, 18.4)],
	"Terrace": [(-13, 10, 0, 12.8, 20, 12.4), (0, 15, 0, 13.2, 30, 12.4), (13.2, 10, 0, 13.2, 20, 12.4)],
	"Hut": [(0, 6, 0, 14.4, 12, 10.4), (9.5, 3.5, 0, 4.6, 7, 8.6)],
	"Tattered": [(0, 10, 0, 19.2, 20, 12.4)],
}
# the shelf beside the rock pack: rows, each house's x and z on it
SHELF = {
	"Cottage": (29850, 610), "Townhouse": (29950, 610), "Farmhouse": (30050, 610), "Hut": (30150, 610),
	"Inn": (29850, 685), "Bridgehouse": (29950, 685), "Mill": (30050, 685), "Smithy": (30150, 685),
	"Clocktower": (29850, 765), "Manor": (29950, 765), "Terrace": (30050, 765), "Tattered": (30150, 765),
}


def bounds(path):
	lo, hi = [math.inf] * 3, [-math.inf] * 3
	for line in open(path):
		if line.startswith("v "):
			v = [float(c) for c in line.split()[1:4]]
			lo = [min(a, b) for a, b in zip(lo, v)]
			hi = [max(a, b) for a, b in zip(hi, v)]
	return [round(c, 3) for c in lo + hi]


data = {"Model": int(A["Houses"]["id"]), "Houses": {}}
for house, boxes in COLLIDE.items():
	parts = {}
	for s in SHEETS:
		parts[s] = {"Id": "rbxassetid://" + A[f"{house}_{s}"]["id"], "Bounds": bounds(os.path.join(ROOT, "art", "kit", house.lower(), f"{house}_{s}.obj"))}
	data["Houses"][house] = {"Parts": parts, "Collide": boxes, "Shelf": SHELF[house]}
payload = json.dumps(data, separators=(",", ":"))
body = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "houses_template.luau"), encoding="utf-8").read().replace("__DATA__", payload)
open(os.path.join(ROOT, "tools", "studio", "place_houses.luau"), "w", encoding="utf-8").write(body)
print("wrote place_houses.luau", len(body))

swap = {}
for entry in A.values():
	for old in entry.get("previous", []):
		swap["rbxassetid://" + old] = "rbxassetid://" + entry["id"]
recolour = f"""-- Generated by tools/art/houses_luau.py. Edit mode. Swaps old house sheets for their new ones everywhere in the place; nothing moves.
local SWAP = game:GetService("HttpService"):JSONDecode([==[{json.dumps(swap, separators=(",", ":"))}]==])
local swapped = 0
for _, root in {{ workspace, game:GetService("ServerStorage"), game:GetService("ReplicatedStorage") }} do
	for _, d in root:GetDescendants() do
		if d:IsA("SurfaceAppearance") and SWAP[d.ColorMap] then
			d.ColorMap = SWAP[d.ColorMap]
			swapped += 1
		end
	end
end
game:GetService("ChangeHistoryService"):SetWaypoint("Recolour houses")
return swapped
"""
open(os.path.join(ROOT, "tools", "studio", "recolour_houses.luau"), "w", encoding="utf-8").write(recolour)
print("wrote recolour_houses.luau", len(swap), "swaps")
