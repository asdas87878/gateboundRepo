"""Writes tools/studio/place_bridge.luau from art/kit/bridge/kit.json, because Studio scripts can't read files.
  python tools/art/bridge_luau.py <model id> <walls sheet id> <top sheet id>
"""
import json
import math
import sys

MODEL, WALLS, TOP = sys.argv[1:4]
KIT = json.load(open("art/kit/bridge/kit.json"))


def box(c):
	"""every collider as: name, centre x y z, yaw, pitch, size x y z, in the bridge's frame"""
	if "A" in c:
		a, b = c["A"], c["B"]
		dx, dy, dz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
		flat = math.hypot(dx, dz)
		return (c["Name"], (a[0] + b[0]) / 2, (a[1] + b[1]) / 2 - c["Height"] / 2, (a[2] + b[2]) / 2, -math.atan2(dz, dx), math.atan2(dy, flat), math.hypot(flat, dy) + 0.4, c["Height"], c["Width"])
	x, y, z = c["Centre"]
	return (c["Name"], x, y, z, 0.0, math.radians(c.get("Pitch", 0)), c["Length"], c["Height"], c["Width"])


rows = ",\n".join('\t\t{ "%s", %.3f, %.3f, %.3f, %.4f, %.4f, %.3f, %.3f, %.3f }' % box(c) for c in KIT["Colliders"])
pieces = ",\n".join('\t\t%s = { %.4f, %.4f, %.4f }' % (name, *p["Centre"]) for name, p in KIT["Pieces"].items())
top_pieces = ", ".join(f"{name} = true" for name in KIT["Sheets"]["Bridge_Top_Color.png"])
sizes = ",\n".join('\t\t%s = { %.3f, %.3f, %.3f }' % (name, *p["Size"]) for name, p in KIT["Pieces"].items())
ux, uz = (KIT["To"][0] - KIT["From"][0]) / KIT["Length"], (KIT["To"][1] - KIT["From"][1]) / KIT["Length"]

out = f"""-- The stone bridge (docs/style/art-style.md), generated by tools/art/bridge_luau.py from art/kit/bridge/kit.json: edit those, not this. Edit mode.
-- Masters in ServerStorage.BridgeKit, the bridge in Workspace.Land1.StoneBridge. Replaces the grey-box BridgeStone blocks; rerun after build_land_small.luau, which brings them back.
-- The meshes have no collision. Walking and blocking come from simple invisible parts in StoneBridge.Colliders.

local CONFIG = {{
	Model = {MODEL},
	Walls = "rbxassetid://{WALLS}",
	Top = "rbxassetid://{TOP}",
	OffsetX = -6000,
	Lift = 1.9, -- Studio's voxel ground reads about 1.9 studs above the height map the kit was fitted to (the water doesn't move)
	From ={{ {KIT["From"][0]}, {KIT["From"][1]} }},
	Right = {{ {ux:.6f}, {uz:.6f} }},
	TopPieces = {{ {top_pieces} }},
	Centres = {{
{pieces},
	}},
	Sizes = {{
{sizes},
	}},
	-- name, centre x y z, yaw, pitch, size x y z (bridge frame: x along, y is world height, z across)
	Colliders = {{
{rows},
	}},
}}
local C = CONFIG

local land = workspace:FindFirstChild("Land1") -- without it (another place), the assembled bridge goes into the kit at the origin
local old = game.ServerStorage:FindFirstChild("BridgeKit")
if old then
	old:Destroy()
end
local masters = Instance.new("Folder")
masters.Name = "BridgeKit"
local model = game:GetService("InsertService"):LoadAsset(C.Model)
for _, d in model:GetDescendants() do
	if d:IsA("MeshPart") then
		local part = d:Clone()
		part.Name = d.Name
		part.Anchored = true
		for _, c in part:GetChildren() do
			c:Destroy()
		end
		local sa = Instance.new("SurfaceAppearance")
		sa.ColorMap = C.TopPieces[d.Name] and C.Top or C.Walls
		sa.Parent = part
		part.Parent = masters
	end
end
model:Destroy()
masters.Parent = game.ServerStorage

if land then
	local gone = land:FindFirstChild("StoneBridge")
	if gone then
		gone:Destroy()
	end
	for _, b in land.Blocks:GetChildren() do
		if b.Name == "BridgeStone" then
			b:Destroy()
		end
	end
end
local bridge = Instance.new("Model")
bridge.Name = "StoneBridge"
local base = land
		and CFrame.fromMatrix(
			Vector3.new(C.From[1] + C.OffsetX, C.Lift, C.From[2]),
			Vector3.new(C.Right[1], 0, C.Right[2]),
			Vector3.yAxis,
			Vector3.new(-C.Right[2], 0, C.Right[1])
		)
	or CFrame.new()
local report = {{ Meshes = {{}}, SizeWrong = {{}} }}
for name, c in C.Centres do
	local master = masters:FindFirstChild(name)
	if not master then
		report.SizeWrong[name] = "missing from the model"
		continue
	end
	local part = master:Clone()
	part.CFrame = base * CFrame.new(c[1], c[2], c[3]) * CFrame.Angles(0, math.pi, 0) -- the glb arrives turned 180 degrees about each part's own centre
	part.CanCollide = false
	part.CanTouch = false
	part.CanQuery = false
	part.RenderFidelity = Enum.RenderFidelity.Precise
	part.CastShadow = true
	part.Parent = bridge
	report.Meshes[name] = string.format("%.1f %.1f %.1f", part.Size.X, part.Size.Y, part.Size.Z)
	local want = C.Sizes[name]
	if math.abs(part.Size.X - want[1]) > 0.5 or math.abs(part.Size.Y - want[2]) > 0.5 or math.abs(part.Size.Z - want[3]) > 0.5 then
		report.SizeWrong[name] = string.format("wanted %.1f %.1f %.1f", want[1], want[2], want[3])
	end
end
local colliders = Instance.new("Folder")
colliders.Name = "Colliders"
colliders.Parent = bridge
for _, r in C.Colliders do
	local p = Instance.new("Part")
	p.Name = r[1]
	p.Anchored = true
	p.Transparency = 1
	p.CanTouch = false
	p.CastShadow = false
	p.Size = Vector3.new(r[7], r[8], r[9])
	p.CFrame = base * CFrame.new(r[2], r[3], r[4]) * CFrame.Angles(0, r[5], 0) * CFrame.Angles(0, 0, r[6])
	p.Parent = colliders
end
bridge.Parent = land or masters
report.Colliders = #colliders:GetChildren()
return game:GetService("HttpService"):JSONEncode(report)
"""
open("tools/studio/place_bridge.luau", "w", encoding="utf-8", newline="\n").write(out)
print("wrote tools/studio/place_bridge.luau,", len(KIT["Colliders"]), "colliders")
